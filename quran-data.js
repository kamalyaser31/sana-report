/**
 * معرفة السورة الواقعة في صفحة معينة من مصحف المدينة
 */
function getSurahByPage(pageNum) {
    const p = parseInt(pageNum, 10);
    if (isNaN(p) || p < 1 || p > 604) return QURAN_SURAHS[0];
    for (let i = QURAN_SURAHS.length - 1; i >= 0; i--) {
        if (p >= QURAN_SURAHS[i].page) {
            return QURAN_SURAHS[i];
        }
    }
    return QURAN_SURAHS[0];
}
